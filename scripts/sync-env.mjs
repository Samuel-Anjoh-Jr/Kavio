#!/usr/bin/env node
// Fans the single root .env out to per-app .env files. This is the ONLY place
// secrets are hand-edited; apps/web/.env.local and apps/api/.env are generated.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const rootEnvPath = join(root, '.env');
const targets = [join(root, 'apps', 'web', '.env.local'), join(root, 'apps', 'api', '.env')];

if (!existsSync(rootEnvPath)) {
  console.error(
    '[env:sync] No root .env found. Copy .env.example to .env and fill in values first.',
  );
  process.exit(1);
}

const lines = readFileSync(rootEnvPath, 'utf8')
  .split(/\r?\n/)
  .filter((line) => {
    const trimmed = line.trim();
    return trimmed.length > 0 && !trimmed.startsWith('#');
  });

const header =
  '# AUTO-GENERATED by scripts/sync-env.mjs from the root .env — do not edit directly.\n\n';
const body = header + lines.join('\n') + '\n';

for (const target of targets) {
  writeFileSync(target, body);
  console.log(`[env:sync] wrote ${target}`);
}
